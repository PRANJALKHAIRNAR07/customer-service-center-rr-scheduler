
import javax.swing.*;
import java.awt.*;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public class GanttChartPanel extends JPanel {

    private static final int LEFT_MARGIN = 85;
    private static final int RIGHT_MARGIN = 30;
    private static final int TOP_MARGIN = 45;
    private static final int ROW_HEIGHT = 55;
    private static final int BAR_HEIGHT = 32;
    private static final int AXIS_HEIGHT = 35;
    private static final int LEGEND_HEIGHT = 45;

    private static final Color[] QUERY_COLORS = {
            new Color(37, 99, 235),
            new Color(13, 148, 136),
            new Color(147, 51, 234),
            new Color(234, 88, 12),
            new Color(219, 39, 119),
            new Color(22, 163, 74),
            new Color(180, 83, 9),
            new Color(79, 70, 229),
            new Color(190, 24, 93),
            new Color(8, 145, 178)
    };

    private static final Pattern LOG_PATTERN = Pattern.compile(
            "Time\\s+(\\d+)\\s+-\\s+(\\d+):\\s+"
            + "(\\S+)\\s+handled by\\s+(\\S+)\\s+"
            + "\\((\\d+)\\s+min\\)"
    );

    private final List<ExecutionSlice> slices =
            new ArrayList<>();

    private final List<String> agentIds =
            new ArrayList<>();

    // LinkedHashMap keeps query colors in first-seen order.
    private final Map<String, Color> queryColors =
            new LinkedHashMap<>();

    private int totalTime;
    private boolean scheduleAvailable;

    public GanttChartPanel() {
        setBackground(Color.WHITE);
        setBorder(BorderFactory.createTitledBorder(
                "Gantt Chart - Agent Execution Timeline"));

        setPreferredSize(new Dimension(850, 260));
        setMinimumSize(new Dimension(450, 180));
    }

    public void setSchedule(
            List<String> executionLog,
            List<Agent> agents,
            int totalTime) {

        slices.clear();
        agentIds.clear();
        queryColors.clear();

        for (Agent agent : agents) {
            agentIds.add(agent.getAgentId());
        }

        this.totalTime = Math.max(totalTime, 1);

        // Read the actual execution log generated by the scheduler.
        for (String entry : executionLog) {
            Matcher matcher = LOG_PATTERN.matcher(entry);

            if (!matcher.matches()) {
                continue;
            }

            int start = Integer.parseInt(matcher.group(1));
            int end = Integer.parseInt(matcher.group(2));
            String queryId = matcher.group(3);
            String agentId = matcher.group(4);
            int duration = Integer.parseInt(matcher.group(5));

            // Ignore malformed intervals.
            if (start < 0 || end <= start
                    || end - start != duration) {
                continue;
            }

            if (!agentIds.contains(agentId)) {
                agentIds.add(agentId);
            }

            if (!queryColors.containsKey(queryId)) {
                Color color = QUERY_COLORS[
                        queryColors.size() % QUERY_COLORS.length];

                queryColors.put(queryId, color);
            }

            slices.add(new ExecutionSlice(
                    start, end, queryId, agentId));
        }

        // Sort the slices chronologically for consistent rendering.
        slices.sort((a, b) -> {
            int comparison = Integer.compare(a.start, b.start);

            if (comparison != 0) {
                return comparison;
            }

            comparison = Integer.compare(a.end, b.end);

            if (comparison != 0) {
                return comparison;
            }

            return a.agentId.compareTo(b.agentId);
        });

        scheduleAvailable = true;

        int chartWidth = Math.max(
                850,
                LEFT_MARGIN + this.totalTime * 90 + RIGHT_MARGIN);

        int chartHeight =
                TOP_MARGIN
                + agentIds.size() * ROW_HEIGHT
                + AXIS_HEIGHT
                + LEGEND_HEIGHT
                + 20;

        setPreferredSize(new Dimension(chartWidth, chartHeight));

        revalidate();
        repaint();
    }

    public void clearSchedule() {
        slices.clear();
        agentIds.clear();
        queryColors.clear();

        totalTime = 0;
        scheduleAvailable = false;

        setPreferredSize(new Dimension(850, 260));

        revalidate();
        repaint();
    }

    @Override
    protected void paintComponent(Graphics graphics) {
        super.paintComponent(graphics);

        Graphics2D g = (Graphics2D) graphics.create();

        g.setRenderingHint(
                RenderingHints.KEY_ANTIALIASING,
                RenderingHints.VALUE_ANTIALIAS_ON);

        if (!scheduleAvailable || slices.isEmpty()) {
            g.setColor(Color.GRAY);
            g.setFont(new Font("Arial", Font.PLAIN, 14));

            String message =
                    "Run the scheduler to display the Gantt chart.";

            FontMetrics metrics = g.getFontMetrics();

            int x = Math.max(
                    15,
                    (getWidth() - metrics.stringWidth(message)) / 2);

            g.drawString(message, x, getHeight() / 2);

            g.dispose();
            return;
        }

        int availableWidth =
                getWidth() - LEFT_MARGIN - RIGHT_MARGIN;

        if (availableWidth <= 0) {
            g.dispose();
            return;
        }

        // One consistent scale for all agent timelines.
        double scale = availableWidth / (double) totalTime;

        g.setFont(new Font("Arial", Font.PLAIN, 11));

        // Draw the agent timelines.
        for (int i = 0; i < agentIds.size(); i++) {
            String agentId = agentIds.get(i);

            int rowY = TOP_MARGIN + i * ROW_HEIGHT;
            int barY = rowY + 5;

            // Agent label.
            g.setFont(new Font("Arial", Font.BOLD, 12));
            g.setColor(new Color(31, 41, 55));
            g.drawString(agentId, 18, barY + 20);

            // Timeline background represents available/idle time.
            g.setColor(new Color(243, 244, 246));
            g.fillRect(
                    LEFT_MARGIN,
                    barY,
                    availableWidth,
                    BAR_HEIGHT);

            // Draw every slice assigned to this agent.
            for (ExecutionSlice slice : slices) {
                if (!slice.agentId.equals(agentId)) {
                    continue;
                }

                int x = LEFT_MARGIN
                        + (int) Math.round(slice.start * scale);

                int endX = LEFT_MARGIN
                        + (int) Math.round(slice.end * scale);

                int width = Math.max(1, endX - x);

                Color queryColor = queryColors.get(slice.queryId);

                g.setColor(queryColor);
                g.fillRoundRect(
                        x, barY, width, BAR_HEIGHT, 6, 6);

                // Subtle border makes adjacent slices easier to distinguish.
                g.setColor(queryColor.darker());
                g.drawRoundRect(
                        x, barY, width, BAR_HEIGHT, 6, 6);

                // Display query ID and interval where space permits.
                String label = slice.queryId;
                String timeLabel =
                        slice.start + "-" + slice.end;

                g.setFont(new Font("Arial", Font.BOLD, 10));
                FontMetrics fm = g.getFontMetrics();

                g.setColor(Color.WHITE);

                if (width >= fm.stringWidth(label) + 10) {
                    int labelX = x
                            + (width - fm.stringWidth(label)) / 2;

                    g.drawString(label, labelX, barY + 13);
                }

                g.setFont(new Font("Arial", Font.PLAIN, 9));
                fm = g.getFontMetrics();

                if (width >= fm.stringWidth(timeLabel) + 8) {
                    int timeX = x
                            + (width - fm.stringWidth(timeLabel)) / 2;

                    g.drawString(timeLabel, timeX, barY + 26);
                }
            }

            // Horizontal divider between agents.
            g.setColor(new Color(229, 231, 235));
            g.drawLine(
                    LEFT_MARGIN,
                    rowY + ROW_HEIGHT - 3,
                    LEFT_MARGIN + availableWidth,
                    rowY + ROW_HEIGHT - 3);
        }

        // Draw the common time axis.
        int axisY = TOP_MARGIN
                + agentIds.size() * ROW_HEIGHT;

        g.setColor(new Color(75, 85, 99));
        g.setFont(new Font("Arial", Font.PLAIN, 11));

        g.drawLine(
                LEFT_MARGIN,
                axisY,
                LEFT_MARGIN + availableWidth,
                axisY);

        // Choose a readable interval between tick marks.
        int tickStep = Math.max(
                1, (int) Math.ceil(totalTime / 12.0));

        for (int time = 0; time <= totalTime; time += tickStep) {
            drawTick(g, time, axisY, scale);
        }

        if (totalTime % tickStep != 0) {
            drawTick(g, totalTime, axisY, scale);
        }

        // Axis caption.
        g.setFont(new Font("Arial", Font.PLAIN, 11));
        String axisCaption = "Simulation time (minutes)";
        FontMetrics fm = g.getFontMetrics();

        g.drawString(
                axisCaption,
                LEFT_MARGIN
                        + (availableWidth - fm.stringWidth(axisCaption)) / 2,
                axisY + 30);

        // Draw a legend using the same colors as the query blocks.
        drawLegend(g, axisY + AXIS_HEIGHT + 8, availableWidth);

        g.dispose();
    }

    private void drawTick(
            Graphics2D g,
            int time,
            int axisY,
            double scale) {

        int x = LEFT_MARGIN
                + (int) Math.round(time * scale);

        g.setColor(new Color(75, 85, 99));
        g.drawLine(x, axisY - 4, x, axisY + 4);

        String label = String.valueOf(time);
        FontMetrics fm = g.getFontMetrics();

        int labelX = x - fm.stringWidth(label) / 2;

        g.drawString(label, labelX, axisY + 16);

        // Vertical guide line helps align slices with the time axis.
        g.setColor(new Color(229, 231, 235));
        g.drawLine(
                x,
                TOP_MARGIN,
                x,
                TOP_MARGIN + agentIds.size() * ROW_HEIGHT - 8);
    }

    private void drawLegend(
            Graphics2D g,
            int y,
            int availableWidth) {

        g.setFont(new Font("Arial", Font.BOLD, 11));
        g.setColor(new Color(31, 41, 55));
        g.drawString("Query legend:", LEFT_MARGIN, y + 13);

        int x = LEFT_MARGIN + 90;
        int maxX = LEFT_MARGIN + availableWidth;

        for (Map.Entry<String, Color> entry
                : queryColors.entrySet()) {

            String queryId = entry.getKey();
            int itemWidth = 75;

            if (x + itemWidth > maxX) {
                // Remaining legend items continue on a new line
                // when the chart is horizontally constrained.
                y += 22;
                x = LEFT_MARGIN + 90;
            }

            g.setColor(entry.getValue());
            g.fillRoundRect(x, y + 3, 12, 12, 3, 3);

            g.setColor(new Color(31, 41, 55));
            g.drawString(queryId, x + 17, y + 13);

            x += itemWidth;
        }
    }

    private static class ExecutionSlice {
        private final int start;
        private final int end;
        private final String queryId;
        private final String agentId;

        private ExecutionSlice(
                int start,
                int end,
                String queryId,
                String agentId) {

            this.start = start;
            this.end = end;
            this.queryId = queryId;
            this.agentId = agentId;
        }
    }
}
